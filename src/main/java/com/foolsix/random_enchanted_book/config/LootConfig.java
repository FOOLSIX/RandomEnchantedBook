package com.foolsix.random_enchanted_book.config;

import net.neoforged.neoforge.common.ModConfigSpec;

/** Loot settings remain in the existing common TOML; book pools live in datapacks. */
public final class LootConfig {
    public static final ModConfigSpec SPEC;
    public static final ChestBookLootConfig CHEST_BOOKS;
    private static final ModConfigSpec.BooleanValue REPLACE_LOOT_BOOKS;
    private static final ModConfigSpec.DoubleValue REPLACEMENT_CHANCE;
    private static volatile double replacementChance;

    static {
        var builder = new ModConfigSpec.Builder();
        builder.push("loot");
        REPLACE_LOOT_BOOKS = builder.comment("Replace enchanted books generated by loot tables with random enchanted books.")
                .define("replaceEnchantedBooks", false);
        REPLACEMENT_CHANCE = builder.comment("Chance per enchanted book to attempt replacement.",
                        "Each enchantment uses the first matching pool in common, uncommon, rare, epic order.")
                .defineInRange("replacementChance", 0.5, 0.0, 1.0);
        CHEST_BOOKS = new ChestBookLootConfig(builder);
        builder.pop();
        SPEC = builder.build();
    }

    private LootConfig() {}

    public static void refresh() {
        replacementChance = REPLACE_LOOT_BOOKS.get() ? REPLACEMENT_CHANCE.get() : 0.0;
        CHEST_BOOKS.refresh();
    }

    public static double replacementChance() {
        return replacementChance;
    }
}
