package com.foolsix.random_enchanted_book.config;

import java.util.ArrayList;
import java.util.List;

import com.foolsix.random_enchanted_book.item.ModItemReg;
import net.minecraft.util.random.WeightedEntry;
import net.minecraft.util.random.WeightedRandomList;
import net.minecraft.world.level.ItemLike;
import net.neoforged.neoforge.common.ModConfigSpec;

public final class ChestBookLootConfig {
    // Keep the total within the range supported by Minecraft's weighted roll.
    private static final int MAX_WEIGHT = Integer.MAX_VALUE / 4;

    private final ModConfigSpec.DoubleValue chance;
    private final ModConfigSpec.IntValue commonWeight;
    private final ModConfigSpec.IntValue uncommonWeight;
    private final ModConfigSpec.IntValue rareWeight;
    private final ModConfigSpec.IntValue epicWeight;
    private volatile Settings settings = new Settings(0.0, WeightedRandomList.create());

    ChestBookLootConfig(ModConfigSpec.Builder builder) {
        builder.comment("Extra random enchanted books generated by chest loot tables.").push("chestBooks");
        chance = builder.comment("Chance to add one random enchanted book when a chest loot table is rolled.")
                .defineInRange("chance", 0.3, 0.0, 1.0);
        commonWeight = weight(builder, "commonWeight", 10);
        uncommonWeight = weight(builder, "uncommonWeight", 5);
        rareWeight = weight(builder, "rareWeight", 2);
        epicWeight = weight(builder, "epicWeight", 1);
        builder.pop();
    }

    private static ModConfigSpec.IntValue weight(ModConfigSpec.Builder builder, String key, int defaultWeight) {
        return builder.comment("Relative weight for the book item. A weight of zero excludes this rarity.")
                .defineInRange(key, defaultWeight, 0, MAX_WEIGHT);
    }

    void refresh() {
        List<WeightedEntry.Wrapper<ItemLike>> books = new ArrayList<>(4);
        addWeightedBook(books, ModItemReg.COMMON_BOOK, commonWeight.get());
        addWeightedBook(books, ModItemReg.UNCOMMON_BOOK, uncommonWeight.get());
        addWeightedBook(books, ModItemReg.RARE_BOOK, rareWeight.get());
        addWeightedBook(books, ModItemReg.EPIC_BOOK, epicWeight.get());
        settings = new Settings(books.isEmpty() ? 0.0 : chance.get(), WeightedRandomList.create(books));
    }

    private static void addWeightedBook(List<WeightedEntry.Wrapper<ItemLike>> books, ItemLike book, int weight) {
        if (weight > 0) {
            books.add(WeightedEntry.wrap(book, weight));
        }
    }

    public Settings settings() {
        return settings;
    }

    public record Settings(double chance, WeightedRandomList<WeightedEntry.Wrapper<ItemLike>> books) {}
}
